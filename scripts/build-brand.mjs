// Size the generated transparent master for browser, website, and GitHub use.
import sharp from 'sharp';
import { readFile, writeFile, copyFile } from 'node:fs/promises';

for (const size of [16, 32, 48, 128, 512]) {
  await sharp('public/logo-source.png').resize(size, size).png().toFile(`public/icon-${size}.png`);
}
await copyFile('public/icon-128.png', 'public/logo.png');
const encoded = async name => (await readFile(`public/${name}`)).toString('base64');
await writeFile('src/brand.js', `// Generated by scripts/build-brand.mjs from public/logo-source.png.\nexport const logoPng = ${JSON.stringify(await encoded('logo.png'))};\nexport const pickerLogo = ${JSON.stringify('data:image/png;base64,' + await encoded('icon-32.png'))};\nexport const logo = '<img src="/logo.png" width="36" height="36" alt="">';\n`);
